let chatCounter = 0;
function handleChat(body) {
  chatCounter += 1;
  const sessionId = body?.session_id || `sess_${Math.random().toString(16).slice(2, 8)}`;
  const turnId = `turn_live_${String(chatCounter).padStart(3, '0')}`;
  const message = String(body?.message ?? '');
  const wantsEmail = /email|send|notify|digest/i.test(message);
  const wantsDocs = /doc|runbook|policy|explain|why|how/i.test(message);

  if (!state.sessions.some((s) => s.id === sessionId)) {
    state.sessions.unshift({
      id: sessionId,
      user_id: body?.user_id || null,
      created_at: iso(),
      preview: message.slice(0, 96),
    });
    state.messages[sessionId] = [];
  }
  state.messages[sessionId] = state.messages[sessionId] ?? [];
  state.messages[sessionId].push({ role: 'user', content: message, created_at: iso() });

  const routes = [];
  if (wantsDocs) {
    routes.push({
      agent: 'research_agent',
      task: 'Retrieve grounding passages from the indexed corpus.',
      reason: 'The request asks about documented behaviour; research owns rag_search.',
    });
  }
  routes.push({
    agent: wantsEmail ? 'ops_agent' : 'code_agent',
    task: wantsEmail ? 'Draft and send the requested message.' : 'Inspect the repository and answer.',
    reason: wantsEmail
      ? 'A side effect on an external system — ops holds the credential and the tool is confirmation-gated.'
      : 'Repo-local work; the code agent is the only agent allow-listed for read_file and git_diff_summarize.',
  });

  const pending = [];
  if (wantsEmail) {
    const c = {
      id: `confirm_${Math.random().toString(16).slice(2, 6)}`,
      session_id: sessionId,
      agent: 'ops_agent',
      tool: 'email_send',
      arguments: {
        to: ['oncall@jarvis.dev'],
        subject: 'Jarvis digest',
        body: `Requested: ${message.slice(0, 160)}`,
      },
      status: 'pending',
    };
    state.confirmations.push(c);
    pending.push(c);
  }

  const text = wantsEmail
    ? 'I have drafted the message and routed it through the confirmation gate — nothing has been sent yet. Approve below and I will deliver it.'
    : `Here is what I found for "${message.slice(0, 60)}": the relevant code path is in \`checkout/pricing.py\`, and the retry policy in the runbook explains the tail latency. Open the trace to see the retrieval and the diff I used.`;

  state.messages[sessionId].push({ role: 'assistant', content: text, created_at: iso() });

  // Synthesise a small trace so "View trace" works for live turns too.
  const evs = [];
  for (const r of routes) {
    evs.push(ev(turnId, sessionId, 'orchestrator', 'route_decision', r, 5, null, 0));
  }
  evs.push(ev(turnId, sessionId, routes[routes.length - 1].agent, 'model_call', {
    iteration: 1, stop_reason: 'end_turn', text, tool_calls: [], parse_error: null,
    prompt_tokens: 640, completion_tokens: 120,
  }, 940, 760, 0));
  evs.push(ev(turnId, sessionId, 'orchestrator', 'final_response', { text, iterations: 1 }, 20, null, 0));
  state.turns.set(turnId, {
    summary: {
      turn_id: turnId,
      session_id: sessionId,
      started: iso(),
      events: evs.length,
      tokens: evs.reduce((a, e) => a + (e.tokens ?? 0), 0),
      routed: routes.map((r) => r.agent),
    },
    events: evs,
  });

  return {
    session_id: sessionId,
    turn_id: turnId,
    text,
    truncated: false,
    route_decisions: routes,
    pending_confirmations: pending,
  };
}

