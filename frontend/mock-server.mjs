function json(res, status, payload) {
  const body = JSON.stringify(payload);
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(body),
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
  });
  res.end(body);
}

async function readBody(req) {
  const chunks = [];
  for await (const c of req) chunks.push(c);
  if (!chunks.length) return null;
  try {
    return JSON.parse(Buffer.concat(chunks).toString('utf8'));
  } catch {
    return null;
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', `http://${req.headers.host ?? 'localhost'}`);
  // Tolerate an /api prefix so the mock also works without the Vite proxy.
  const path = url.pathname.replace(/^\/api(?=\/|$)/, '') || '/';
  const method = req.method ?? 'GET';

  if (method === 'OPTIONS') return json(res, 204, {});

  try {
    if (path === '/health') return json(res, 200, state.health);

    if (path === '/sessions') return json(res, 200, state.sessions);

    const msgMatch = path.match(/^\/sessions\/([^/]+)\/messages$/);
    if (msgMatch) {
      const id = decodeURIComponent(msgMatch[1]);
      const msgs = state.messages[id];
      if (!msgs) return json(res, 404, { detail: `Unknown session '${id}'` });
      return json(res, 200, msgs);
    }

    if (path === '/traces/turns') {
      const sid = url.searchParams.get('session_id');
      const limit = Number(url.searchParams.get('limit') ?? 50);
      let turns = [...state.turns.values()].map((t) => t.summary);
      if (sid) turns = turns.filter((t) => t.session_id === sid);
      turns.sort((a, b) => Date.parse(b.started) - Date.parse(a.started));
      return json(res, 200, turns.slice(0, Number.isFinite(limit) ? limit : 50));
    }

    const turnMatch = path.match(/^\/traces\/turn\/([^/]+)$/);
    if (turnMatch) {
      const id = decodeURIComponent(turnMatch[1]);
      const turn = state.turns.get(id);
      if (!turn) return json(res, 404, { detail: `No trace for turn '${id}'` });
      await sleep(LATENCY_MS / 2);
      return json(res, 200, { turn_id: id, events: turn.events });
    }

    if (path === '/metrics') return json(res, 200, metrics());

    if (path === '/confirmations') {
      const sid = url.searchParams.get('session_id');
      const list = state.confirmations.filter(
        (c) => c.status === 'pending' && (!sid || c.session_id === sid),
      );
      return json(res, 200, list);
    }

    const confirmMatch = path.match(/^\/confirm\/([^/]+)$/);
    if (confirmMatch && method === 'POST') {
      const id = decodeURIComponent(confirmMatch[1]);
      const body = await readBody(req);
      const c = state.confirmations.find((x) => x.id === id);
      if (!c) return json(res, 404, { detail: `Unknown confirmation '${id}'` });
      await sleep(LATENCY_MS);
      c.status = body?.approve ? 'confirmed' : 'rejected';
      return json(res, 200, {
        id,
        status: c.status,
        result: body?.approve
          ? { delivered: true, message_id: `msg_${Math.random().toString(16).slice(2, 8)}` }
          : null,
      });
    }

    if (path === '/chat' && method === 'POST') {
      const body = await readBody(req);
      if (!body || typeof body.message !== 'string' || !body.message.trim()) {
        return json(res, 422, { detail: 'message must be a non-empty string' });
      }
      await sleep(LATENCY_MS * 2);
      return json(res, 200, handleChat(body));
    }

    if (path === '/eval/runs') return json(res, 200, state.evalRuns);

    const runMatch = path.match(/^\/eval\/runs\/([^/]+)$/);
    if (runMatch) {
      const id = decodeURIComponent(runMatch[1]);
      const run = state.evalRuns.find((r) => r.run_id === id);
      if (!run) return json(res, 404, { detail: `Unknown run '${id}'` });
      return json(res, 200, run);
    }

    if (path === '/eval/run' && method === 'POST') {
      await sleep(Math.max(1500, LATENCY_MS * 6));
      const prevRun = state.evalRuns[0] ?? null;
      const index = state.evalRuns.length;
      const shape = {
        hash: 'cfg_7a8b9c',
        passed: Object.fromEntries(
          CATEGORIES.map((c) => {
            const prev = prevRun?.scores_by_category?.[c];
            const base = prev ? Math.round(prev.pass_rate * CATEGORY_TOTALS[c]) : CATEGORY_TOTALS[c] - 1;
            const jitter = Math.random() < 0.25 ? -1 : Math.random() < 0.5 ? 1 : 0;
            return [c, Math.max(0, Math.min(CATEGORY_TOTALS[c], base + jitter))];
          }),
        ),
      };
      const prevShape = prevRun
        ? {
            passed: Object.fromEntries(
              CATEGORIES.map((c) => [
                c,
                Math.round((prevRun.scores_by_category?.[c]?.pass_rate ?? 0) * CATEGORY_TOTALS[c]),
              ]),
            ),
          }
        : null;
      const card = buildScorecard(index, shape, prevShape, prevRun?.run_id ?? null);
      card.ts = iso();
      state.evalRuns.unshift(card);
      return json(res, 200, card);
    }

    return json(res, 404, { detail: `No route for ${method} ${path}` });
  } catch (err) {
    return json(res, 500, { detail: err instanceof Error ? err.message : String(err) });
  }
});

server.listen(PORT, () => {
  process.stdout.write(`jarvis mock backend listening on http://localhost:${PORT}\n`);
});
