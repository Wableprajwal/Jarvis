function buildScorecard(index, shape, prevShape, prevRunId) {
  const scores = {};
  for (const cat of CATEGORIES) {
    const total = CATEGORY_TOTALS[cat];
    const passed = shape.passed[cat];
    scores[cat] = { pass_rate: Number((passed / total).toFixed(4)), passed, total };
  }
  const regressions = [];
  if (prevShape) {
    for (const cat of CATEGORIES) {
      const prev = prevShape.passed[cat] / CATEGORY_TOTALS[cat];
      const cur = shape.passed[cat] / CATEGORY_TOTALS[cat];
      if (cur < prev - 1e-9) {
        regressions.push({
          category: cat,
          previous: Number(prev.toFixed(4)),
          current: Number(cur.toFixed(4)),
        });
      }
    }
  }
  return {
    run_id: `run_${String(index + 1).padStart(3, '0')}`,
    ts: iso(-(RUN_SHAPES.length - index) * 6 * 60 * MINUTE),
    config_hash: shape.hash,
    scores_by_category: scores,
    regressions,
    previous_run_id: prevRunId,
    details: buildDetails(index),
  };
}

RUN_SHAPES.forEach((shape, i) => {
  const prev = i > 0 ? RUN_SHAPES[i - 1] : null;
  const prevId = i > 0 ? `run_${String(i).padStart(3, '0')}` : null;
  state.evalRuns.push(buildScorecard(i, shape, prev, prevId));
});
state.evalRuns.reverse(); // newest first

