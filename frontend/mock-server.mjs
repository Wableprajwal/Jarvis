let seqCounter = 0;
function ev(turnId, sessionId, agent, type, payload, latency, tokens, tsOffset) {
  seqCounter += 1;
  return {
    seq: seqCounter,
    id: `evt_${turnId}_${String(seqCounter).padStart(3, '0')}`,
    session_id: sessionId,
    agent_name: agent,
    turn_id: turnId,
    event_type: type,
    payload,
    latency_ms: latency ?? null,
    tokens: tokens ?? null,
    ts: iso(tsOffset),
  };
}

